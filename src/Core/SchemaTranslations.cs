        private static Dictionary<string, string> Table(string code, Dictionary<string, string> french, Dictionary<string, string> dutch)
        {
            return code == "fr" ? french : code == "nl" ? dutch : null;
        }

        private static string Lookup(string code, Dictionary<string, string> french, Dictionary<string, string> dutch, string key)
        {
            Dictionary<string, string> table = Table(code, french, dutch);
            if (table == null) return null;
            string value;
            return table.TryGetValue(key, out value) ? value : null;
        }

        private static string Pick(string code, string translation, string english, string german)
        {
            if (!String.IsNullOrEmpty(translation)) return translation;
            if (!String.IsNullOrEmpty(english)) return english;
            return german;
        }

        public static string FieldLabel(string code, string section, string entry, string german, string english)
        {
            if (code == "de") return german;
            if (code == "en") return english;
            return Pick(code, Lookup(code, FrenchLabels, DutchLabels, (section ?? String.Empty) + "/" + (entry ?? String.Empty)), english, german);
        }

